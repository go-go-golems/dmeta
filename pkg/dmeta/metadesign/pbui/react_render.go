func renderConstJSON(symbol string, value any) (string, error) {
	b, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	buf.WriteString("// Generated by DMETA PBUI React target. Do not edit by hand.\n")
	buf.WriteString("// This registry preserves PBUI/Semantic/Interaction metadata for introspection surfaces.\n\n")
	buf.WriteString("export const ")
	buf.WriteString(symbol)
	buf.WriteString(" = ")
	buf.Write(b)
	buf.WriteString(" as const;\n")
	return buf.String(), nil
}

