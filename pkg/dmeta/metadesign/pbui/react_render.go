func renderCommandParser() string {
	return `// Generated by DMETA PBUI React target. Do not edit by hand.

export interface ParsedPBUICommand {
  kind: 'empty' | 'action';
  actionId?: string;
  raw: string;
}

export function parsePBUICommand(raw: string): ParsedPBUICommand {
  const trimmed = raw.trim();
  if (!trimmed) return { kind: 'empty', raw };
  return { kind: 'action', actionId: trimmed.split(/\s+/)[0], raw };
}
`
}

func renderPackageReadme(plan ReactPlan) string {
	return fmt.Sprintf("# %s\n\nGenerated PBUI React scaffold plan.\n\nThis package is generated from the DMETA PBUI MetaDesignSystem. It keeps actions,\nobject types, and presentations visible as first-class descriptors so generated\ncomponents can be inspected and traced back to Semantic IR, Interaction IR, and\nPBUI lowering rules.\n\n- MetaDesignSystem: `%s`\n- Target: `%s`\n- Object descriptors: %d\n- Action descriptors: %d\n- Presentation components: %d\n", plan.PackageName, plan.MetaDesignSystem, plan.TargetID, len(plan.ObjectDescriptors), len(plan.ActionDescriptors), len(plan.PresentationPlans))
}

func renderPresenterHook(plan PresentationPlan) string {
	return fmt.Sprintf(`// Generated by DMETA PBUI React target. Do not edit by hand.
// Presenter intent: %s

export interface %sViewModel {
  presentationType: %q;
  semanticId?: string;
  label?: string;
}

export function use%sPresentation(seed: Partial<%sViewModel> = {}): %sViewModel {
  return {
    presentationType: %q,
    ...seed,
  };
}
`, tsComment(plan.PresenterIntent), plan.ComponentName, plan.PresentationTypeID, plan.ComponentName, plan.ComponentName, plan.ComponentName, plan.PresentationTypeID)
}

func renderComponent(plan PresentationPlan) string {
	return fmt.Sprintf(`// Generated by DMETA PBUI React target. Do not edit by hand.
// Presenter intent: %s
// Recognizer intent: %s

export interface %sProps {
  semanticId?: string;
  label?: string;
}

export function %s(props: %sProps) {
  return (
    <section
      data-dmeta-meta-design-system="pbui"
      data-dmeta-codegen-target="react"
      data-dmeta-presentation-type=%q
      data-dmeta-representations=%q
      data-dmeta-actions=%q
    >
      <strong>%s</strong>
      {props.label ? <span>{props.label}</span> : null}
    </section>
  );
}
`, tsComment(plan.PresenterIntent), tsComment(plan.RecognizerIntent), plan.ComponentName, plan.ComponentName, plan.ComponentName, plan.PresentationTypeID, strings.Join(plan.SourceRepresentations, ","), strings.Join(plan.SourceActions, ","), plan.ComponentName)
}

func renderMetadata(provenance ReactFileProvenance) (string, error) {
	b, err := json.MarshalIndent(provenance, "", "  ")
	if err != nil {
		return "", err
	}
	return string(b) + "\n", nil
}

func renderStories(plan PresentationPlan) string {
	return fmt.Sprintf(`// Generated by DMETA PBUI React target. Do not edit by hand.

import type { Meta, StoryObj } from '@storybook/react';
import { %s } from './%s';

const meta = {
  title: 'PBUI/%s',
  component: %s,
  parameters: {
    docs: {
      description: {
        component: %q,
      },
    },
  },
} satisfies Meta<typeof %s>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Default: Story = {
  args: {
    label: %q,
  },
};
`, plan.ComponentName, plan.ComponentName, plan.ComponentName, plan.ComponentName, plan.Rationale, plan.ComponentName, plan.PresentationTypeID)
}

func renderBarrel(symbol string) string {
	return fmt.Sprintf("export * from './%s';\n", filepath.Base(symbol))
}

func tsComment(value string) string {
	return strings.ReplaceAll(value, "\n", " ")
}
