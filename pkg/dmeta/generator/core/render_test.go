package core

import (
	"context"
	"path/filepath"
	"runtime"
	"strings"
	"testing"

	"github.com/go-go-golems/dmeta/pkg/dmeta/validator"
)

func TestGenerateCurrentCoreSmoke(t *testing.T) {
	root := repoRoot(t)
	pkg, err := validator.LoadPackage(context.Background(), filepath.Join(root, "sources", "dmeta-ir"))
	if err != nil {
		t.Fatalf("load package: %v", err)
	}

	files, err := Generate(pkg, "generated/dmeta-core")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if got, want := len(files), 7; got != want {
		t.Fatalf("expected %d files, got %d", want, got)
	}

	byPath := map[string]string{}
	for _, file := range files {
		byPath[file.Path] = string(file.Content)
		if !strings.Contains(string(file.Content), "Code generated by dmeta generate-core") {
			t.Fatalf("%s missing generated header", file.Path)
		}
	}

	assertContains(t, byPath["generated/dmeta-core/archetypes.ts"], "export type ArchetypeId")
	assertContains(t, byPath["generated/dmeta-core/archetypes.ts"], "longDescription")
	assertContains(t, byPath["generated/dmeta-core/capabilities.ts"], "export type CapabilityId")
	assertContains(t, byPath["generated/dmeta-core/presentations.ts"], "export type PresentationId")
	assertContains(t, byPath["generated/dmeta-core/actions.ts"], "export type ActionId")
	assertContains(t, byPath["generated/dmeta-core/PresentationRef.ts"], "export type PresentationRef")
	assertContains(t, byPath["generated/dmeta-core/actionMatching.ts"], "actionsForPresentationRef")
}

func TestGenerateCurrentCoreDeterministic(t *testing.T) {
	root := repoRoot(t)
	pkg, err := validator.LoadPackage(context.Background(), filepath.Join(root, "sources", "dmeta-ir"))
	if err != nil {
		t.Fatalf("load package: %v", err)
	}

	first, err := Generate(pkg, "generated/dmeta-core")
	if err != nil {
		t.Fatalf("first generate: %v", err)
	}
	second, err := Generate(pkg, "generated/dmeta-core")
	if err != nil {
		t.Fatalf("second generate: %v", err)
	}
	if len(first) != len(second) {
		t.Fatalf("file count mismatch: %d != %d", len(first), len(second))
	}
	for i := range first {
		if first[i].Path != second[i].Path {
			t.Fatalf("path mismatch at %d: %s != %s", i, first[i].Path, second[i].Path)
		}
		if string(first[i].Content) != string(second[i].Content) {
			t.Fatalf("content mismatch for %s", first[i].Path)
		}
	}
}

func repoRoot(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller failed")
	}
	return filepath.Clean(filepath.Join(filepath.Dir(file), "..", "..", "..", ".."))
}

func assertContains(t *testing.T, s string, want string) {
	t.Helper()
	if !strings.Contains(s, want) {
		t.Fatalf("expected generated content to contain %q", want)
	}
}
