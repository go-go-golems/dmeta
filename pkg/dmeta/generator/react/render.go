func webTypeScriptPrelude(_ ScaffoldPlan, component ComponentPlan, file PlannedFile) string {
	metadataPath := relativeMetadataPath(component, file)
	return fmt.Sprintf(`// Code generated by dmeta scaffold-react. This is a generated template, not the promoted source.
// Metadata: %s
// To promote: copy/rename into hand-owned src/components/%s/%s, remove .template from filenames, wire adapters/Storybook, and update src/dmeta/widgetRegistry.ts.
// Do not edit this generated file directly; edit the IR/generator or promote first.

`, metadataPath, storybookKind(component), component.ComponentName)
}

func relativeMetadataPath(component ComponentPlan, file PlannedFile) string {
	metadataPath := filepath.Join(component.ComponentDir, metadataFileName(component))
	if file.Path == "" {
		return "./" + metadataFileName(component)
	}
	rel, err := filepath.Rel(filepath.Dir(file.Path), metadataPath)
	if err != nil {
		return "./" + metadataFileName(component)
	}
	rel = filepath.ToSlash(rel)
	if rel == metadataFileName(component) || !strings.HasPrefix(rel, ".") {
		rel = "./" + rel
	}
	return rel
}

func metadataFileName(component ComponentPlan) string {
	return component.ComponentName + ".metadata.json"
}

func webGeneratedMetadata(plan ScaffoldPlan, component ComponentPlan, file PlannedFile) genmeta.GeneratedFileMetadata {
	generated := plan.Generated
	if generated.By == "" {
		generated.By = "dmeta scaffold-react"
	}
	meta := genmeta.GeneratedFileMetadata{
		Generated: generated,
		Artifact: genmeta.ArtifactInfo{
			Path:       file.Path,
			Kind:       file.Kind,
			Language:   reactLanguageForPath(file.Path),
			Symbol:     file.Symbol,
			Promotable: webFileIsPromotable(file.Kind),
		},
		Pipeline: genmeta.PipelineInfo{
			SemanticRoot:     plan.SemanticRoot,
			InteractionsRoot: plan.InteractionsRoot,
			MetaDesignSystem: "web",
			Target:           plan.TargetID,
			Passes:           passesFromComponent(component),
		},
		Sources: []genmeta.SourceReference{
			{Path: plan.SemanticRoot, Role: "semantic package", Why: "Provides domain types, archetypes, capabilities, and examples used by Web lowering."},
			{Path: plan.InteractionsRoot, Role: "interaction package", Why: "Provides action and representation obligations lowered into Web widget obligations."},
			{Path: plan.WebRoot, Role: "Web MetaDesignSystem", Why: "Provides widget templates, Web lowering rules, and target-independent web obligations."},
			{Path: plan.TargetFile, Role: "React target", Why: "Provides React target defaults and file kinds for this scaffold."},
		},
		Semantics: &genmeta.SemanticGuidance{
			DomainTypes:     append([]string{}, component.SourceDomainTypes...),
			Representations: append([]string{}, component.RealizesRepresentations...),
			Actions:         append([]string{}, component.RealizesActions...),
			SourceRules:     append([]string{}, component.SourceRules...),
		},
		Web: &genmeta.WebGuidance{
			TemplateID:    component.TemplateID,
			Variant:       component.Variant,
			Slots:         append([]string{}, component.Slots...),
			VisualStates:  append([]string{}, component.VisualStates...),
			EventBindings: append([]string{}, component.EventBindings...),
			ComponentSystem: &genmeta.ComponentSystemGuidance{
				Kind:        component.ComponentKind,
				Specificity: component.ComponentSpecificity,
				Family:      component.ComponentFamily,
				Role:        component.ComponentRole,
				Lifecycle:   component.ComponentLifecycle,
			},
			Composition: &genmeta.ComponentCompositionInfo{
				Uses:     componentDependencyIDs(component),
				Provides: append([]string{}, component.Template.Composition.Provides...),
			},
		},
		React: &genmeta.ReactGuidance{
			PackageName:   component.PackageName,
			Files:         generatedReactFileRefs(component.Files),
			ComponentPath: component.ComponentDir,
			Props:         reactPropContractRefs(component),
			Events:        reactEventContractRefs(component),
		},
		Guidance: &genmeta.HumanGuidance{
			Summary: "Generated Web React scaffold. Promote intentionally before hand editing and keep the JSON metadata sidecar visible to maintain Semantic IR and Web MetaDesignSystem context.",
			ImplementationNotes: []string{
				"Use the sibling metadata JSON sidecar to trace props, slots, visual states, and event bindings back to Web lowering obligations.",
				"When promoted, copy or rename *.template.* files into hand-owned source, remove the .template suffix, update Storybook, and update src/dmeta/widgetRegistry.ts.",
			},
		},
	}
	return genmeta.WithDefaults(meta)
}

func generatedReactFileRefs(files []PlannedFile) []genmeta.FileRef {
	refs := make([]genmeta.FileRef, 0, len(files))
	for _, file := range files {
		refs = append(refs, genmeta.FileRef{Kind: file.Kind, Path: file.Path, Symbol: file.Symbol})
	}
	return refs
}

func componentDependencyIDs(component ComponentPlan) []string {
	ids := make([]string, 0, len(component.Template.Composition.Uses))
	for _, dep := range component.Template.Composition.Uses {
		if dep.Template != "" {
			ids = append(ids, dep.Template)
			continue
		}
		if dep.Component != "" {
			ids = append(ids, dep.Component)
		}
	}
	return ids
}

func reactPropContractRefs(component ComponentPlan) []genmeta.ReactPropContractRef {
	refs := []genmeta.ReactPropContractRef{}
	for _, propName := range sortedPropNames(component.Template.Contract.Props) {
		contract := component.Template.Contract.Props[propName]
		if strings.HasSuffix(propName, "Props") {
			for _, fieldName := range sortedFieldNames(contract.Fields) {
				field := contract.Fields[fieldName]
				refs = append(refs, genmeta.ReactPropContractRef{Name: fieldName, Type: contractTypeLabel(field), Source: firstNonEmpty(field.Source, contract.Source), SourceRef: firstNonEmpty(field.SourceRef, contract.SourceRef), Required: field.Required, Values: append([]string{}, field.Values...), Description: field.Description})
			}
			continue
		}
		refs = append(refs, genmeta.ReactPropContractRef{Name: propName, Type: "object", Source: contract.Source, SourceRef: contract.SourceRef, Required: contract.Required, Description: contract.Description})
	}
	return refs
}

func reactEventContractRefs(component ComponentPlan) []genmeta.ReactEventContractRef {
	refs := []genmeta.ReactEventContractRef{}
	for _, name := range sortedEventNames(component.Template.Contract.Events) {
		event := component.Template.Contract.Events[name]
		refs = append(refs, genmeta.ReactEventContractRef{Name: name, ActionRef: event.ActionRef, PayloadType: event.PayloadType, Source: event.Source, Required: event.Required, Description: event.Description})
	}
	for name, slot := range component.Template.Contract.ActionSlots {
		refs = append(refs, genmeta.ReactEventContractRef{Name: name, ActionRef: slot.ActionRef, PayloadType: firstNonEmpty(slot.PayloadType, slot.Accepts), Source: slot.Source, Description: slot.Description})
	}
	return refs
}

func contractTypeLabel(field validator.PropField) string {
	return firstNonEmpty(field.Type, field.TypeRef, field.ItemTypeRef)
}

func webFileIsPromotable(kind string) bool {
	switch kind {
	case "component", "types", "stories", "style", "adapter_todo", "readme", "barrel":
		return true
	default:
		return false
	}
}

func reactLanguageForPath(path string) string {
	switch filepath.Ext(path) {
	case ".tsx":
		return "tsx"
	case ".ts":
		return "ts"
	case ".json":
		return "json"
	case ".css":
		return "css"
	case ".md":
		return "markdown"
	default:
		return "text"
	}
}
