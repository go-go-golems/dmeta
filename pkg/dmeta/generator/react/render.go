func componentDependencyIDs(component ComponentPlan) []string {
	ids := make([]string, 0, len(component.Template.Composition.Uses))
	for _, dep := range component.Template.Composition.Uses {
		if dep.Template != "" {
			ids = append(ids, dep.Template)
			continue
		}
		if dep.Component != "" {
			ids = append(ids, dep.Component)
		}
	}
	return ids
}

func reactPropContractRefs(component ComponentPlan) []genmeta.ReactPropContractRef {
	refs := []genmeta.ReactPropContractRef{}
	for _, propName := range sortedPropNames(component.Template.Contract.Props) {
		contract := component.Template.Contract.Props[propName]
		if strings.HasSuffix(propName, "Props") {
			for _, fieldName := range sortedFieldNames(contract.Fields) {
				field := contract.Fields[fieldName]
				refs = append(refs, genmeta.ReactPropContractRef{Name: fieldName, Type: contractTypeLabel(field), Source: firstNonEmpty(field.Source, contract.Source), SourceRef: firstNonEmpty(field.SourceRef, contract.SourceRef), Required: field.Required, Values: append([]string{}, field.Values...), Description: field.Description})
			}
			continue
		}
		refs = append(refs, genmeta.ReactPropContractRef{Name: propName, Type: "object", Source: contract.Source, SourceRef: contract.SourceRef, Required: contract.Required, Description: contract.Description})
	}
	return refs
}

func reactEventContractRefs(component ComponentPlan) []genmeta.ReactEventContractRef {
	refs := []genmeta.ReactEventContractRef{}
	for _, name := range sortedEventNames(component.Template.Contract.Events) {
		event := component.Template.Contract.Events[name]
		refs = append(refs, genmeta.ReactEventContractRef{Name: name, ActionRef: event.ActionRef, PayloadType: event.PayloadType, Source: event.Source, Required: event.Required, Description: event.Description})
	}
	for name, slot := range component.Template.Contract.ActionSlots {
		refs = append(refs, genmeta.ReactEventContractRef{Name: name, ActionRef: slot.ActionRef, PayloadType: firstNonEmpty(slot.PayloadType, slot.Accepts), Source: slot.Source, Description: slot.Description})
	}
	return refs
}

func contractTypeLabel(field validator.PropField) string {
	return firstNonEmpty(field.Type, field.TypeRef, field.ItemTypeRef)
}

func webFileIsPromotable(kind string) bool {
	switch kind {
	case "component", "types", "stories", "style", "readme", "barrel":
		return true
	default:
		return false
	}
}

func reactLanguageForPath(path string) string {
	switch filepath.Ext(path) {
	case ".tsx":
		return "tsx"
	case ".ts":
		return "ts"
	case ".json":
		return "json"
	case ".css":
		return "css"
	case ".md":
		return "markdown"
	default:
		return "text"
	}
}
