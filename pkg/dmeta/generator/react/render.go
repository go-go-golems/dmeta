func reactFileRefs(files []PlannedFile) []ReactFileRef {
	refs := make([]ReactFileRef, 0, len(files))
	for _, file := range files {
		refs = append(refs, ReactFileRef{Kind: file.Kind, Path: file.Path, Symbol: file.Symbol})
	}
	return refs
}

func commaList(values []string) string {
	if len(values) == 0 {
		return "none"
	}
	return strings.Join(values, ", ")
}

func sampleStoryArgs(component ComponentPlan) string {
	if len(component.Template.Contract.Props) == 0 && len(component.Template.Contract.Events) == 0 {
		return ""
	}
	var b strings.Builder
	for _, propName := range sortedPropNames(component.Template.Contract.Props) {
		contract := component.Template.Contract.Props[propName]
		if strings.HasSuffix(propName, "Props") {
			for _, fieldName := range sortedFieldNames(contract.Fields) {
				field := contract.Fields[fieldName]
				if !field.Required {
					continue
				}
				b.WriteString(fmt.Sprintf("    %s: %s,\n", fieldName, sampleValueForPropField(field, fieldName)))
			}
			continue
		}
		if !contract.Required {
			continue
		}
		b.WriteString(fmt.Sprintf("    %s: {\n", propName))
		for _, fieldName := range sortedFieldNames(contract.Fields) {
			field := contract.Fields[fieldName]
			if !field.Required {
				continue
			}
			b.WriteString(fmt.Sprintf("      %s: %s,\n", fieldName, sampleValueForPropField(field, fieldName)))
		}
		b.WriteString("    },\n")
	}
	for _, eventName := range sortedEventNames(component.Template.Contract.Events) {
		event := component.Template.Contract.Events[eventName]
		if event.Required {
			b.WriteString(fmt.Sprintf("    %s: () => undefined,\n", eventName))
		}
	}
	return b.String()
}

func sampleValueForPropField(field validator.PropField, fieldName string) string {
	if len(field.Values) > 0 {
		return tsString(field.Values[0])
	}
	switch tsTypeFromPropField(field) {
	case "string":
		return tsString(sampleStringForField(fieldName))
	case "number":
		return "0"
	case "boolean":
		return "false"
	default:
		if strings.EqualFold(field.TypeRef, "ReactNode") || strings.EqualFold(field.Type, "ReactNode") {
			return tsString(sampleStringForField(fieldName))
		}
		if strings.HasSuffix(tsTypeFromPropField(field), "[]") {
			return "[]"
		}
		return "undefined"
	}
}

func sampleStringForField(fieldName string) string {
	switch strings.ToLower(fieldName) {
	case "children", "label", "title", "name":
		return "Sample"
	case "id":
		return "sample-id"
	default:
		return "Sample"
	}
}

func renderContractProps(component ComponentPlan) string {
	if len(component.Template.Contract.Props) == 0 {
		return ""
	}
	var b strings.Builder
	for _, propName := range sortedPropNames(component.Template.Contract.Props) {
		contract := component.Template.Contract.Props[propName]
		if strings.HasSuffix(propName, "Props") {
			for _, fieldName := range sortedFieldNames(contract.Fields) {
				field := contract.Fields[fieldName]
				b.WriteString(renderPropComment(field, "  "))
				b.WriteString(fmt.Sprintf("  %s%s: %s;\n", fieldName, optionalSuffix(!field.Required), tsTypeFromPropField(field)))
			}
			continue
		}
		b.WriteString(renderInterfaceComment(contract, "  "))
		b.WriteString(fmt.Sprintf("  %s%s: {\n", propName, optionalSuffix(!contract.Required)))
		for _, fieldName := range sortedFieldNames(contract.Fields) {
			field := contract.Fields[fieldName]
			b.WriteString(renderPropComment(field, "    "))
			b.WriteString(fmt.Sprintf("    %s%s: %s;\n", fieldName, optionalSuffix(!field.Required), tsTypeFromPropField(field)))
		}
		b.WriteString("  };\n")
	}
	return b.String()
}

func renderInterfaceComment(contract validator.InterfaceContract, indent string) string {
	parts := []string{}
	if contract.Source != "" {
		parts = append(parts, "source: "+contract.Source)
	}
	if contract.SourceRef != "" {
		parts = append(parts, "source_ref: "+contract.SourceRef)
	}
	if contract.Description != "" {
		parts = append(parts, contract.Description)
	}
	if len(parts) == 0 {
		return ""
	}
	return indent + "/** " + strings.Join(parts, "; ") + " */\n"
}

func renderPropComment(field validator.PropField, indent string) string {
	parts := []string{}
	if field.Source != "" {
		parts = append(parts, "source: "+field.Source)
	}
	if field.SourceRef != "" {
		parts = append(parts, "source_ref: "+field.SourceRef)
	}
	if field.Description != "" {
		parts = append(parts, field.Description)
	}
	if len(parts) == 0 {
		return ""
	}
	return indent + "/** " + strings.Join(parts, "; ") + " */\n"
}

func sortedPropNames(props map[string]validator.InterfaceContract) []string {
	names := make([]string, 0, len(props))
	for name := range props {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func sortedFieldNames(fields map[string]validator.PropField) []string {
	names := make([]string, 0, len(fields))
	for name := range fields {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func sortedEventNames(events map[string]validator.EventContract) []string {
	names := make([]string, 0, len(events))
	for name := range events {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func optionalSuffix(optional bool) string {
	if optional {
		return "?"
	}
	return ""
}

func tsTypeFromPropField(field validator.PropField) string {
	if len(field.Values) > 0 {
		values := make([]string, 0, len(field.Values))
		for _, value := range field.Values {
			values = append(values, tsString(value))
		}
		return strings.Join(values, " | ")
	}
	if field.ItemTypeRef != "" {
		return tsTypeFromContractType(field.ItemTypeRef) + "[]"
	}
	if field.TypeRef != "" {
		return tsTypeFromContractType(field.TypeRef)
	}
	return tsTypeFromContractType(field.Type)
}

func tsTypeFromContractType(contractType string) string {
	t := strings.TrimSpace(contractType)
	if t == "" {
		return "unknown"
	}
	if strings.HasSuffix(t, "[]") {
		return tsTypeFromContractType(strings.TrimSuffix(t, "[]")) + "[]"
	}
	switch t {
	case "string", "number", "boolean", "unknown", "any", "void":
		return t
	case "integer", "float", "double":
		return "number"
	default:
		return "unknown"
	}
}

func storybookKind(component ComponentPlan) string {
	if component.ComponentKind == "" {
		return "components"
	}
	return defaultComponentDir(component.ComponentKind)
}

func passesFromComponent(component ComponentPlan) []string {
	for _, file := range component.Files {
		if len(file.Provenance.Passes) > 0 {
			return append([]string{}, file.Provenance.Passes...)
		}
	}
	return nil
}

func callbackName(action string) string {
	parts := strings.FieldsFunc(action, func(r rune) bool { return r == '_' || r == '-' || r == '.' })
	for i, part := range parts {
		if part == "" {
			continue
		}
		parts[i] = strings.ToUpper(part[:1]) + part[1:]
	}
	return "on" + strings.Join(parts, "")
}

func defaultVisualState(component ComponentPlan) string {
	if len(component.VisualStates) == 0 {
		return "default"
	}
	return component.VisualStates[0]
}

func tsStringArray(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, tsString(value))
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

func storyDescription(component ComponentPlan) string {
	parts := []string{
		fmt.Sprintf("Generated React scaffold for Web template %s.", component.TemplateID),
		"MetaDesignSystem: web.",
	}
	if len(component.RealizesRepresentations) > 0 {
		parts = append(parts, "Representations: "+strings.Join(component.RealizesRepresentations, ", ")+".")
	}
	if len(component.RealizesActions) > 0 {
		parts = append(parts, "Actions: "+strings.Join(component.RealizesActions, ", ")+".")
	}
	return strings.Join(parts, " ")
}

func tsString(value string) string {
	b, _ := json.Marshal(value)
	return string(b)
}

