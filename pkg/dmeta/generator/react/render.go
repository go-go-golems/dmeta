const generatedHeader = "// Code generated by dmeta scaffold-react from Web MetaDesignSystem obligations. DO NOT EDIT generated files directly.\n\n"

type GeneratedFile struct {
	Path      string
	Kind      string
	Lifecycle string
	Content   []byte
}

type MetadataSidecar struct {
	GeneratedBy      string             `json:"generatedBy"`
	MetaDesignSystem string             `json:"metaDesignSystem"`
	CodegenTarget    string             `json:"codegenTarget"`
	ComponentName    string             `json:"componentName"`
	TemplateID       string             `json:"templateId"`
	Variant          string             `json:"variant,omitempty"`
	Realizes         RealizesMetadata   `json:"realizes"`
	Web              WebMetadata        `json:"web"`
	React            ReactMetadata      `json:"react"`
	Provenance       ProvenanceMetadata `json:"provenance"`
}

type RealizesMetadata struct {
	Representations []string `json:"representations,omitempty"`
	Actions         []string `json:"actions,omitempty"`
}

type WebMetadata struct {
	Slots         []string `json:"slots,omitempty"`
	VisualStates  []string `json:"visualStates,omitempty"`
	EventBindings []string `json:"eventBindings,omitempty"`
}

type ReactMetadata struct {
	PackageName string         `json:"packageName,omitempty"`
	Files       []ReactFileRef `json:"files,omitempty"`
}

type ReactFileRef struct {
	Kind   string `json:"kind"`
	Path   string `json:"path"`
	Symbol string `json:"symbol,omitempty"`
}

type ProvenanceMetadata struct {
	DomainTypes []string `json:"domainTypes,omitempty"`
	SourceRules []string `json:"sourceRules,omitempty"`
	Passes      []string `json:"passes,omitempty"`
}

func Generate(plan ScaffoldPlan) ([]GeneratedFile, error) {
	files := make([]GeneratedFile, 0, len(plan.Files)+len(plan.Components)*8)
	for _, file := range plan.Files {
		content, err := renderPackageFile(plan, file)
		if err != nil {
			return nil, err
		}
		files = append(files, GeneratedFile{Path: file.Path, Kind: file.Kind, Lifecycle: file.Lifecycle, Content: content})
	}
	for _, component := range plan.Components {
		for _, file := range component.Files {
			content, err := renderComponentFile(plan, component, file)
			if err != nil {
				return nil, err
			}
			files = append(files, GeneratedFile{Path: file.Path, Kind: file.Kind, Lifecycle: file.Lifecycle, Content: content})
		}
	}
	return files, nil
}

func RenderMetadataSidecar(plan ScaffoldPlan, component ComponentPlan) ([]byte, error) {
	metadata := webGeneratedMetadata(plan, component, PlannedFile{Path: filepath.Join(component.ComponentDir, metadataFileName(component)), Kind: "metadata", Symbol: component.ComponentName + "Metadata"})
	return genmeta.RenderJSON(metadata)
}

func legacyMetadataSidecar(component ComponentPlan) MetadataSidecar {
	return MetadataSidecar{
		GeneratedBy:      "dmeta scaffold-react",
		MetaDesignSystem: "web",
		CodegenTarget:    "react",
		ComponentName:    component.ComponentName,
		TemplateID:       component.TemplateID,
		Variant:          component.Variant,
		Realizes: RealizesMetadata{
			Representations: append([]string{}, component.RealizesRepresentations...),
			Actions:         append([]string{}, component.RealizesActions...),
		},
		Web: WebMetadata{
			Slots:         append([]string{}, component.Slots...),
			VisualStates:  append([]string{}, component.VisualStates...),
			EventBindings: append([]string{}, component.EventBindings...),
		},
		React: ReactMetadata{
			PackageName: component.PackageName,
			Files:       reactFileRefs(component.Files),
		},
		Provenance: ProvenanceMetadata{
			DomainTypes: append([]string{}, component.SourceDomainTypes...),
			SourceRules: append([]string{}, component.SourceRules...),
			Passes:      passesFromComponent(component),
		},
	}
}

func GenerateMetadataSidecars(plan ScaffoldPlan) ([]GeneratedFile, error) {
	files := make([]GeneratedFile, 0, len(plan.Components))
	for _, component := range plan.Components {
		content, err := RenderMetadataSidecar(plan, component)
		if err != nil {
			return nil, err
		}
		files = append(files, GeneratedFile{Path: filepath.Join(component.ComponentDir, metadataFileName(component)), Kind: "metadata", Lifecycle: lifecycleForKind(component, "metadata"), Content: content})
	}
	return files, nil
}

func renderPackageFile(plan ScaffoldPlan, file PlannedFile) ([]byte, error) {
	switch file.Kind {
	case "package_index":
		var b bytes.Buffer
		b.WriteString(generatedHeader)
		b.WriteString(fmt.Sprintf("// Instance: %s\n", plan.InstanceID))
		b.WriteString(fmt.Sprintf("// MetaDesignSystem: %s\n", plan.MetaDesignSystem))
		b.WriteString(fmt.Sprintf("// Target: %s\n\n", plan.TargetID))
		for _, component := range plan.Components {
			b.WriteString(fmt.Sprintf("export * from \"%s\";\n", component.PackageExportPath))
		}
		return b.Bytes(), nil
	case "manifest":
		return renderGeneratedManifest(plan)
	default:
		return nil, fmt.Errorf("unsupported package file kind %q", file.Kind)
	}
}

func renderGeneratedManifest(plan ScaffoldPlan) ([]byte, error) {
	type manifestPaths struct {
		Dir      string `json:"dir,omitempty"`
		Types    string `json:"types,omitempty"`
		Metadata string `json:"metadata,omitempty"`
		Stories  string `json:"stories,omitempty"`
		Style    string `json:"style,omitempty"`
		Barrel   string `json:"barrel,omitempty"`
	}
	type promotedPaths struct {
		Dir       string `json:"dir"`
		Component string `json:"component"`
		Style     string `json:"style"`
		Stories   string `json:"stories"`
		Barrel    string `json:"barrel"`
	}
	type manifestSemantics struct {
		DomainTypes     []string `json:"domainTypes,omitempty"`
		Representations []string `json:"representations,omitempty"`
		Actions         []string `json:"actions,omitempty"`
		SourceRules     []string `json:"sourceRules,omitempty"`
	}
	type manifestComponent struct {
		TemplateID    string            `json:"templateId"`
		ComponentName string            `json:"componentName"`
		Kind          string            `json:"kind"`
		Specificity   string            `json:"specificity,omitempty"`
		Family        string            `json:"family,omitempty"`
		Role          string            `json:"role,omitempty"`
		Variant       string            `json:"variant,omitempty"`
		Generated     manifestPaths     `json:"generated"`
		Promoted      promotedPaths     `json:"promoted"`
		Semantics     manifestSemantics `json:"semantics,omitempty"`
	}
	type manifest struct {
		SchemaVersion int                   `json:"schemaVersion"`
		Generated     genmeta.GeneratedInfo `json:"generated"`
		PackageName   string                `json:"packageName,omitempty"`
		TargetID      string                `json:"targetId,omitempty"`
		Components    []manifestComponent   `json:"components"`
	}

	packageRoot := packageRootFromOutputDir(plan.OutputDir)
	components := make([]manifestComponent, 0, len(plan.Components))
	for _, component := range plan.Components {
		generated := manifestPaths{Dir: relToPackage(packageRoot, component.ComponentDir)}
		for _, file := range component.Files {
			rel := relToPackage(packageRoot, file.Path)
			switch file.Kind {
			case "types":
				generated.Types = rel
			case "metadata":
				generated.Metadata = rel
			case "stories":
				generated.Stories = rel
			case "style":
				generated.Style = rel
			case "barrel":
				generated.Barrel = rel
			}
		}
		promotedDir := filepath.Join(packageRoot, "src", "components", defaultComponentDir(component.ComponentKind), component.ComponentName)
		components = append(components, manifestComponent{
			TemplateID:    component.TemplateID,
			ComponentName: component.ComponentName,
			Kind:          component.ComponentKind,
			Specificity:   component.ComponentSpecificity,
			Family:        component.ComponentFamily,
			Role:          component.ComponentRole,
			Variant:       component.Variant,
			Generated:     generated,
			Promoted: promotedPaths{
				Dir:       relToPackage(packageRoot, promotedDir),
				Component: relToPackage(packageRoot, filepath.Join(promotedDir, component.ComponentName+".tsx")),
				Style:     relToPackage(packageRoot, filepath.Join(promotedDir, component.ComponentName+".module.css")),
				Stories:   relToPackage(packageRoot, filepath.Join(promotedDir, component.ComponentName+".stories.tsx")),
				Barrel:    relToPackage(packageRoot, filepath.Join(promotedDir, "index.ts")),
			},
			Semantics: manifestSemantics{
				DomainTypes:     append([]string{}, component.SourceDomainTypes...),
				Representations: append([]string{}, component.RealizesRepresentations...),
				Actions:         append([]string{}, component.RealizesActions...),
				SourceRules:     append([]string{}, component.SourceRules...),
			},
		})
	}

	content, err := json.MarshalIndent(manifest{SchemaVersion: 1, Generated: plan.Generated, PackageName: plan.PackageName, TargetID: plan.TargetID, Components: components}, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(content, '\n'), nil
}

func packageRootFromOutputDir(outputDir string) string {
	return filepath.Dir(filepath.Dir(filepath.Dir(outputDir)))
}

func relToPackage(packageRoot string, path string) string {
	rel, err := filepath.Rel(packageRoot, path)
	if err != nil {
		return filepath.ToSlash(path)
	}
	return filepath.ToSlash(rel)
}

func renderComponentFile(plan ScaffoldPlan, component ComponentPlan, file PlannedFile) ([]byte, error) {
	switch file.Kind {
	case "component":
		return []byte(renderComponent(plan, component, file)), nil
	case "types":
		return []byte(renderTypes(plan, component, file)), nil
	case "metadata":
		content, err := RenderMetadataSidecar(plan, component)
		if err != nil {
			return nil, err
		}
		return content, nil
	case "stories":
		return []byte(renderStories(plan, component, file)), nil
	case "style":
		return []byte(renderStyles(component)), nil
	case "barrel":
		return []byte(renderBarrel(plan, component, file)), nil
	case "readme":
		return []byte(renderReadme(component)), nil
	default:
		return nil, fmt.Errorf("unsupported React file kind %q", file.Kind)
	}
}

func renderTypes(plan ScaffoldPlan, component ComponentPlan, file PlannedFile) string {
	var b bytes.Buffer
	b.WriteString(webTypeScriptPrelude(plan, component, file))
	if componentUsesReactNode(component) {
		b.WriteString("import type { ReactNode } from \"react\";\n\n")
	}
	b.WriteString(fmt.Sprintf("export type %sSlotName =\n", component.ComponentName))
	if len(component.Slots) == 0 {
		b.WriteString("  never;\n")
	} else {
		for _, slot := range component.Slots {
			b.WriteString(fmt.Sprintf("  | %q\n", slot))
		}
		b.WriteString(";\n")
	}
	b.WriteString("\n")
	b.WriteString(fmt.Sprintf("export type %sVisualState =\n", component.ComponentName))
	if len(component.VisualStates) == 0 {
		b.WriteString("  | \"default\"\n")
		b.WriteString(";\n")
	} else {
		for _, state := range component.VisualStates {
			b.WriteString(fmt.Sprintf("  | %q\n", state))
		}
		b.WriteString(";\n")
	}
	b.WriteString("\n")
	b.WriteString(fmt.Sprintf("export type %sProps = {\n", component.ComponentName))
	b.WriteString("  className?: string;\n")
	b.WriteString(fmt.Sprintf("  visualState?: %sVisualState;\n", component.ComponentName))
	b.WriteString("  slots?: Partial<Record<")
	b.WriteString(component.ComponentName)
	b.WriteString("SlotName, unknown>>;\n")
	b.WriteString(renderContractProps(component))
	for _, eventBinding := range component.EventBindings {
		b.WriteString(fmt.Sprintf("  %s?: (payload: unknown) => void;\n", callbackName(eventBinding)))
	}
	for _, eventName := range sortedEventNames(component.Template.Contract.Events) {
		event := component.Template.Contract.Events[eventName]
		b.WriteString(fmt.Sprintf("  %s%s: %s;\n", eventName, optionalSuffix(!event.Required), tsCallbackType(event.PayloadType)))
	}
	b.WriteString("};\n")
	return b.String()
}

func renderComponent(plan ScaffoldPlan, component ComponentPlan, file PlannedFile) string {
	return fmt.Sprintf(`%simport styles from "./%s.module.css";
import type { %sProps, %sSlotName } from "./%s.types";

/**
 * %s
 *
 * React target scaffold for Web template %s.
 * MetaDesignSystem: web.
 * Component kind: %s.
 * Component specificity: %s.
 * Component role: %s.
 * Realizes representations: %s.
 * Realizes actions: %s.
 */
export function %s(props: %sProps) {
  const { className, visualState = %q, slots = {} } = props;
  const rootClassName = [styles.root, className].filter(Boolean).join(" ");

  return (
    <section
      className={rootClassName}
      data-dmeta-meta-design-system="web"
      data-dmeta-codegen-target="react"
      data-dmeta-widget-template=%q
      data-dmeta-representations=%q
      data-dmeta-actions=%q
      data-dmeta-visual-state={visualState}
    >
      <header className={styles.header}>
        <strong>%s</strong>
        <span>{visualState}</span>
      </header>
      <dl className={styles.slots}>
        {(%s as %sSlotName[]).map((slotName) => (
          <div key={slotName} className={styles.slot} data-dmeta-slot={slotName}>
            <dt>{slotName}</dt>
            <dd>{String(slots[slotName] ?? "")}</dd>
          </div>
        ))}
      </dl>
    </section>
  );
}

export default %s;
`, webTypeScriptPrelude(plan, component, file), generatedFileBase(component), component.ComponentName, component.ComponentName, generatedFileBase(component), component.ComponentName, component.TemplateID, component.ComponentKind, component.ComponentSpecificity, component.ComponentRole, strings.Join(component.RealizesRepresentations, ", "), strings.Join(component.RealizesActions, ", "), component.ComponentName, component.ComponentName, defaultVisualState(component), component.TemplateID, strings.Join(component.RealizesRepresentations, ","), strings.Join(component.RealizesActions, ","), component.ComponentName, tsStringArray(component.Slots), component.ComponentName, component.ComponentName)
}

