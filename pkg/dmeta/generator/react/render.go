func relativeMetadataPath(component ComponentPlan, file PlannedFile) string {
	metadataPath := filepath.Join(component.ComponentDir, metadataFileName(component))
	if file.Path == "" {
		return "./" + metadataFileName(component)
	}
	rel, err := filepath.Rel(filepath.Dir(file.Path), metadataPath)
	if err != nil {
		return "./" + metadataFileName(component)
	}
	rel = filepath.ToSlash(rel)
	if rel == metadataFileName(component) || !strings.HasPrefix(rel, ".") {
		rel = "./" + rel
	}
	return rel
}

